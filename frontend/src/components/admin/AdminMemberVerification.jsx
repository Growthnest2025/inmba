import React, {
  useEffect,
  useMemo,
  useState,
} from "react";

import {
  toast,
} from "react-toastify";

import {
  verifyAdminMember,
} from "../../services/admin.service";

import {
  getApiErrorMessage,
} from "../../utils/apiError";

import "./AdminMemberVerification.css";
import { toText } from "../../utils/commonHelpers";

/* =========================================================
   STATUS OPTIONS
========================================================= */

const STATUS_OPTIONS = [
  {
    value: "approved",
    label: "Approve",
    icon: "fas fa-circle-check",
    description:
      "Approve membership and activate the referral workflow.",
  },

  {
    value: "pending",
    label: "Pending",
    icon: "fas fa-clock",
    description:
      "Keep this member under administrative review.",
  },

  {
    value: "rejected",
    label: "Reject",
    icon: "fas fa-circle-xmark",
    description:
      "Reject the current membership application.",
  },
];

/* =========================================================
   SEND METHOD OPTIONS

   Source behaviour:

   email:
   Referral link email attempt.

   otp:
   OTP is generated by current backend and
   returned in the response message.

   It is NOT an implemented SMS send flow.
========================================================= */

const SEND_METHODS = [
  {
    value: "email",
    label: "Referral Email",
    icon: "fas fa-envelope",
    description:
      "Send the generated referral link to the member email.",
  },

  {
    value: "otp",
    label: "Generate OTP",
    icon: "fas fa-key",
    description:
      "Generate an approval OTP using the existing backend flow.",
  },
];

/* =========================================================
   HELPERS
========================================================= */

const normalizeStatus = (
  value
) => {
  const status =
    toText(
      value,
      "pending"
    ).toLowerCase();

  if (
    status === "approved" ||
    status === "rejected"
  ) {
    return status;
  }

  return "pending";
};

/* =========================================================
   ADMIN MEMBER VERIFICATION
========================================================= */

export default function AdminMemberVerification({
  member,
  memberId: passedMemberId,
  onUpdated,
}) {
  const memberId =
    passedMemberId ??
    member?.id ??
    member?.member_id ??
    member?.memberId ??
    null;

  const currentStatus =
    normalizeStatus(
      member?.payment_status
    );

  const [
    selectedStatus,
    setSelectedStatus,
  ] =
    useState(
      currentStatus
    );

  const [
    referralId,
    setReferralId,
  ] =
    useState(
      toText(
        member?.referral_id
      )
    );

  const [
    sendMethod,
    setSendMethod,
  ] =
    useState("email");

  const [
    submitting,
    setSubmitting,
  ] =
    useState(false);

  const [
    formError,
    setFormError,
  ] =
    useState("");

  const [
    confirmationOpen,
    setConfirmationOpen,
  ] =
    useState(false);

  /* =======================================================
     SYNC MEMBER
  ======================================================= */

  useEffect(
    () => {
      setSelectedStatus(
        normalizeStatus(
          member?.payment_status
        )
      );

      setReferralId(
        toText(
          member?.referral_id
        )
      );

      setFormError("");
    },
    [
      member?.payment_status,
      member?.referral_id,
    ]
  );

  /* =======================================================
     MEMBER NAME
  ======================================================= */

  const memberName =
    useMemo(
      () => {
        const fullName =
          [
            member?.first_name,
            member?.last_name,
          ]
            .filter(Boolean)
            .join(" ")
            .trim();

        return (
          fullName ||
          member?.login_id ||
          "INMBA Member"
        );
      },
      [
        member?.first_name,
        member?.last_name,
        member?.login_id,
      ]
    );

  /* =======================================================
     SELECTED CONFIG
  ======================================================= */

  const selectedConfig =
    useMemo(
      () =>
        STATUS_OPTIONS.find(
          (
            option
          ) =>
            option.value ===
            selectedStatus
        ) ||
        STATUS_OPTIONS[1],
      [
        selectedStatus,
      ]
    );

  /* =======================================================
     STATUS CHANGE
  ======================================================= */

  const handleStatusChange = (
    value
  ) => {
    if (submitting) {
      return;
    }

    setSelectedStatus(
      value
    );

    setFormError("");
  };

  /* =======================================================
     REFERRAL CHANGE
  ======================================================= */

  const handleReferralChange = (
    event
  ) => {
    const nextValue =
      event.target.value
        .replace(
          /\s/g,
          ""
        )
        .slice(
          0,
          50
        );

    setReferralId(
      nextValue
    );

    setFormError("");
  };

  /* =======================================================
     OPEN CONFIRMATION
  ======================================================= */

  const handlePrepareSubmit = (
    event
  ) => {
    event.preventDefault();

    if (
      !memberId
    ) {
      setFormError(
        "Member ID is missing."
      );

      return;
    }

    if (
      ![
        "approved",
        "pending",
        "rejected",
      ].includes(
        selectedStatus
      )
    ) {
      setFormError(
        "Select a valid member status."
      );

      return;
    }

    setFormError("");

    setConfirmationOpen(
      true
    );
  };

  /* =======================================================
     SUBMIT VERIFICATION

     POST /admin_verify/:id

     FormData:
     status
     referral_id
     send_method
  ======================================================= */

  const handleConfirmSubmit =
    async () => {
      if (
        submitting ||
        !memberId
      ) {
        return;
      }

      try {
        setSubmitting(
          true
        );

        setFormError("");

        const result =
          await verifyAdminMember(
            memberId,
            {
              status:
                selectedStatus,

              /*
                Existing referral ID is preserved.

                For approval:
                blank referral ID means backend
                generates a new unique referral ID.
              */

              referralId,

              sendMethod,
            }
          );

        setConfirmationOpen(
          false
        );

        toast.success(
          result.message ||
            `Member status updated to ${selectedStatus}.`
        );

        if (
          typeof onUpdated ===
          "function"
        ) {
          await onUpdated();
        }
      } catch (
        requestError
      ) {
        setConfirmationOpen(
          false
        );

        const message =
          getApiErrorMessage(
            requestError,
            requestError
              ?.apiMessage ||
              "Unable to update member status."
          );

        setFormError(
          message
        );

        toast.error(
          message
        );
      } finally {
        setSubmitting(
          false
        );
      }
    };

  return (
    <>
      <section className="inmba-admin-verification-card">
        {/* ===============================================
            HEADER
        =============================================== */}

        <header className="inmba-admin-verification-header">
          <div>
            <span className="inmba-admin-verification-header-icon">
              <i
                className="fas fa-user-check"
                aria-hidden="true"
              ></i>
            </span>

            <div>
              <p>
                Administrative Action
              </p>

              <h3>
                Member Verification
              </h3>
            </div>
          </div>

          <CurrentStatus
            status={
              currentStatus
            }
          />
        </header>

        {/* ===============================================
            BODY
        =============================================== */}

        <form
          className="inmba-admin-verification-form"
          onSubmit={
            handlePrepareSubmit
          }
        >
          {/* MEMBER */}

          <div className="inmba-admin-verification-member">
            <span>
              {toText(
                member?.first_name,
                "M"
              )
                .charAt(0)
                .toUpperCase()}
            </span>

            <div>
              <small>
                Updating Member
              </small>

              <strong>
                {memberName}
              </strong>

              <p>
                Login ID:{" "}
                {toText(
                  member?.login_id,
                  "Not available"
                )}
              </p>
            </div>
          </div>

          {/* =============================================
              STATUS
          ============================================= */}

          <div className="inmba-admin-verification-section">
            <div className="inmba-admin-verification-section-title">
              <span>
                1
              </span>

              <div>
                <strong>
                  Membership Status
                </strong>

                <small>
                  Select the new status for this member.
                </small>
              </div>
            </div>

            <div className="inmba-admin-verification-status-grid">
              {STATUS_OPTIONS.map(
                (
                  option
                ) => (
                  <button
                    key={
                      option.value
                    }
                    type="button"
                    className={`inmba-admin-verification-status-option inmba-admin-verification-status-${option.value} ${
                      selectedStatus ===
                      option.value
                        ? "inmba-admin-verification-status-selected"
                        : ""
                    }`}
                    onClick={() =>
                      handleStatusChange(
                        option.value
                      )
                    }
                    disabled={
                      submitting
                    }
                  >
                    <span>
                      <i
                        className={
                          option.icon
                        }
                        aria-hidden="true"
                      ></i>
                    </span>

                    <div>
                      <strong>
                        {
                          option.label
                        }
                      </strong>

                      <small>
                        {
                          option.description
                        }
                      </small>
                    </div>

                    <i
                      className={
                        selectedStatus ===
                        option.value
                          ? "fas fa-circle-check"
                          : "far fa-circle"
                      }
                      aria-hidden="true"
                    ></i>
                  </button>
                )
              )}
            </div>
          </div>

          {/* =============================================
              APPROVAL OPTIONS
          ============================================= */}

          {selectedStatus ===
            "approved" && (
            <div className="inmba-admin-verification-approval-options">
              <div className="inmba-admin-verification-section">
                <div className="inmba-admin-verification-section-title">
                  <span>
                    2
                  </span>

                  <div>
                    <strong>
                      Referral ID
                    </strong>

                    <small>
                      Keep the existing referral ID or leave it blank
                      to let the backend generate one automatically.
                    </small>
                  </div>
                </div>

                <div className="inmba-admin-verification-field">
                  <label htmlFor="admin-member-referral-id">
                    Referral ID
                  </label>

                  <div>
                    <i
                      className="fas fa-link"
                      aria-hidden="true"
                    ></i>

                    <input
                      id="admin-member-referral-id"
                      type="text"
                      value={
                        referralId
                      }
                      onChange={
                        handleReferralChange
                      }
                      placeholder="Auto generate when blank"
                      autoComplete="off"
                      disabled={
                        submitting
                      }
                    />
                  </div>

                  <small>
                    Existing:{" "}
                    <strong>
                      {toText(
                        member?.referral_id,
                        "No referral ID"
                      )}
                    </strong>
                  </small>
                </div>
              </div>

              {/* SEND METHOD */}

              <div className="inmba-admin-verification-section">
                <div className="inmba-admin-verification-section-title">
                  <span>
                    3
                  </span>

                  <div>
                    <strong>
                      Approval Delivery
                    </strong>

                    <small>
                      Select the existing backend notification method.
                    </small>
                  </div>
                </div>

                <div className="inmba-admin-verification-method-grid">
                  {SEND_METHODS.map(
                    (
                      method
                    ) => (
                      <label
                        key={
                          method.value
                        }
                        className={`inmba-admin-verification-method ${
                          sendMethod ===
                          method.value
                            ? "inmba-admin-verification-method-active"
                            : ""
                        }`}
                      >
                        <input
                          type="radio"
                          name="send_method"
                          value={
                            method.value
                          }
                          checked={
                            sendMethod ===
                            method.value
                          }
                          onChange={() =>
                            setSendMethod(
                              method.value
                            )
                          }
                          disabled={
                            submitting
                          }
                        />

                        <span>
                          <i
                            className={
                              method.icon
                            }
                            aria-hidden="true"
                          ></i>
                        </span>

                        <div>
                          <strong>
                            {
                              method.label
                            }
                          </strong>

                          <small>
                            {
                              method.description
                            }
                          </small>
                        </div>
                      </label>
                    )
                  )}
                </div>
              </div>

              {/* PAYMENT RULE */}

              <div className="inmba-admin-verification-payment-rule">
                <span>
                  <i
                    className="fas fa-wallet"
                    aria-hidden="true"
                  ></i>
                </span>

                <div>
                  <strong>
                    Payment Check Is Enforced by Backend
                  </strong>

                  <p>
                    Approval will fail when the member has no
                    recorded payment or bank details. The React
                    frontend does not bypass this rule.
                  </p>
                </div>
              </div>
            </div>
          )}

          {/* =============================================
              PENDING MESSAGE
          ============================================= */}

          {selectedStatus ===
            "pending" && (
            <div className="inmba-admin-verification-context inmba-admin-verification-context-pending">
              <i
                className="fas fa-clock"
                aria-hidden="true"
              ></i>

              <div>
                <strong>
                  Keep Under Review
                </strong>

                <p>
                  The member remains in pending status and can be
                  reviewed again later.
                </p>
              </div>
            </div>
          )}

          {/* =============================================
              REJECTED MESSAGE
          ============================================= */}

          {selectedStatus ===
            "rejected" && (
            <div className="inmba-admin-verification-context inmba-admin-verification-context-rejected">
              <i
                className="fas fa-circle-xmark"
                aria-hidden="true"
              ></i>

              <div>
                <strong>
                  Reject Membership
                </strong>

                <p>
                  This changes the member payment status to rejected.
                  The backend does not accept a rejection-reason field
                  on this route.
                </p>
              </div>
            </div>
          )}

          {/* ERROR */}

          {formError && (
            <div
              className="inmba-admin-verification-error"
              role="alert"
            >
              <i
                className="fas fa-triangle-exclamation"
                aria-hidden="true"
              ></i>

              <span>
                {formError}
              </span>
            </div>
          )}

          {/* SUBMIT */}

          <div className="inmba-admin-verification-submit-row">
            <div>
              <small>
                Selected Action
              </small>

              <strong>
                <i
                  className={
                    selectedConfig.icon
                  }
                  aria-hidden="true"
                ></i>

                {
                  selectedConfig.label
                }
              </strong>
            </div>

            <button
              type="submit"
              disabled={
                submitting
              }
              className={`inmba-admin-verification-submit inmba-admin-verification-submit-${selectedStatus}`}
            >
              {submitting ? (
                <>
                  <i
                    className="fas fa-spinner fa-spin"
                    aria-hidden="true"
                  ></i>

                  Updating...
                </>
              ) : (
                <>
                  Confirm{" "}
                  {
                    selectedConfig.label
                  }

                  <i
                    className="fas fa-arrow-right"
                    aria-hidden="true"
                  ></i>
                </>
              )}
            </button>
          </div>
        </form>
      </section>

      {/* ===================================================
          CONFIRMATION MODAL
      =================================================== */}

      {confirmationOpen && (
        <div
          className="inmba-admin-verification-modal-overlay"
          role="presentation"
        >
          <section
            className="inmba-admin-verification-modal"
            role="dialog"
            aria-modal="true"
            aria-labelledby="admin-verification-confirm-title"
          >
            <span
              className={`inmba-admin-verification-modal-icon inmba-admin-verification-modal-icon-${selectedStatus}`}
            >
              <i
                className={
                  selectedConfig.icon
                }
                aria-hidden="true"
              ></i>
            </span>

            <p>
              Confirm Administrative Action
            </p>

            <h3 id="admin-verification-confirm-title">
              {
                selectedConfig.label
              }{" "}
              {memberName}?
            </h3>

            <span className="inmba-admin-verification-modal-description">
              Status will change from{" "}
              <strong>
                {currentStatus}
              </strong>{" "}
              to{" "}
              <strong>
                {selectedStatus}
              </strong>.
            </span>

            {selectedStatus ===
              "approved" && (
              <div className="inmba-admin-verification-modal-summary">
                <div>
                  <span>
                    Referral ID
                  </span>

                  <strong>
                    {referralId ||
                      "Auto Generate"}
                  </strong>
                </div>

                <div>
                  <span>
                    Delivery
                  </span>

                  <strong>
                    {sendMethod ===
                    "email"
                      ? "Referral Email"
                      : "Generate OTP"}
                  </strong>
                </div>
              </div>
            )}

            <div className="inmba-admin-verification-modal-actions">
              <button
                type="button"
                onClick={() =>
                  setConfirmationOpen(
                    false
                  )
                }
                disabled={
                  submitting
                }
              >
                Cancel
              </button>

              <button
                type="button"
                className={`inmba-admin-verification-modal-confirm inmba-admin-verification-modal-confirm-${selectedStatus}`}
                onClick={
                  handleConfirmSubmit
                }
                disabled={
                  submitting
                }
              >
                {submitting ? (
                  <>
                    <i
                      className="fas fa-spinner fa-spin"
                      aria-hidden="true"
                    ></i>

                    Updating
                  </>
                ) : (
                  <>
                    Yes,{" "}
                    {
                      selectedConfig.label
                    }

                    <i
                      className="fas fa-check"
                      aria-hidden="true"
                    ></i>
                  </>
                )}
              </button>
            </div>
          </section>
        </div>
      )}
    </>
  );
}

/* =========================================================
   CURRENT STATUS
========================================================= */

function CurrentStatus({
  status,
}) {
  const details =
    STATUS_OPTIONS.find(
      (
        option
      ) =>
        option.value ===
        status
    );

  const label =
    details?.label ||
    "Pending";

  const icon =
    details?.icon ||
    "fas fa-clock";

  return (
    <span
      className={`inmba-admin-verification-current-status inmba-admin-verification-current-${status}`}
    >
      <i
        className={
          icon
        }
        aria-hidden="true"
      ></i>

      {label}
    </span>
  );
}