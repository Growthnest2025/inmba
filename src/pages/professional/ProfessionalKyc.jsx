function KycUpload({
  label,
  required = false,
  requirement = null,
  name,
  imageOnly = false,
  file,
  existing,
  error = "",
  onChange,
  onRemove,
  disabled = false,
}) {
  const selectedName =
    file?.name ||
    getFileName(
      existing
    );

  return (
    <div
      className={[
        "professional-kyc-upload-card",

        error
          ? "has-error"
          : "",
      ]
        .filter(
          Boolean
        )
        .join(
          " "
        )}
    >
      <div className="professional-kyc-upload-card-heading">
        <div>
          <span>
            {label}

            {required && (
              <b>
                *
              </b>
            )}

            <RequirementBadge
              requirement={
                requirement
              }
            />
          </span>

          <small>
            {imageOnly
              ? "JPG / PNG · Max 5 MB"
              : "PDF / JPG / PNG · Max 5 MB"}
          </small>
        </div>

        <div className="professional-kyc-private-mini-badge">
          <i className="fa-solid fa-lock" />

          Secure
        </div>
      </div>

      {selectedName ? (
        <div className="professional-kyc-selected-file">
          <div className="professional-kyc-selected-file-icon">
            <i
              className={
                imageOnly
                  ? "fa-solid fa-image"
                  : "fa-solid fa-file-shield"
              }
            />
          </div>

          <div className="professional-kyc-selected-file-info">
            <strong>
              {
                selectedName
              }
            </strong>

            <span>
              {file
                ? "Ready to upload"
                : "Previously uploaded"}
            </span>
          </div>

          {!disabled && (
            <button
              type="button"
              onClick={
                onRemove
              }
              title="Remove file"
            >
              <i className="fa-solid fa-xmark" />
            </button>
          )}
        </div>
      ) : (
        <label className="professional-kyc-upload-box">
          <input
            type="file"
            name={
              name
            }
            accept={
              imageOnly
                ? ".jpg,.jpeg,.png,image/jpeg,image/png"
                : ".pdf,.jpg,.jpeg,.png,application/pdf,image/jpeg,image/png"
            }
            onChange={
              onChange
            }
            disabled={
              disabled
            }
          />

          <i className="fa-solid fa-cloud-arrow-up" />

          <strong>
            Choose File
          </strong>

          <span>
            Click to select document
          </span>
        </label>
      )}

      {error && (
        <small className="professional-kyc-field-error">
          <i className="fa-solid fa-circle-exclamation" />

          {error}
        </small>
      )}
    </div>
  );
}