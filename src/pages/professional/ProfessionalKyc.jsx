const validateFile = (
  file,
  imageOnly = false
) => {
  if (!file) {
    return "";
  }

  const imageTypes = [
    "image/jpeg",
    "image/jpg",
    "image/png",
  ];

  const documentTypes = [
    ...imageTypes,
    "application/pdf",
  ];

  const allowedTypes =
    imageOnly
      ? imageTypes
      : documentTypes;

  if (
    file.type &&
    !allowedTypes.includes(
      file.type
    )
  ) {
    return imageOnly
      ? "Only JPG and PNG images are allowed."
      : "Only PDF, JPG and PNG files are allowed.";
  }

  const maxSize =
    5 *
    1024 *
    1024;

  if (
    file.size >
    maxSize
  ) {
    return "File size must be below 5 MB.";
  }

  return "";
};

