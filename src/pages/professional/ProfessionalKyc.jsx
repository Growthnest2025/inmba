const getProfessionalKycRequirementMeta = (
  item = {}
) => {
  if (item.readOnly) {
    return {
      label: "System Generated",
      tone: "system",
    };
  }

  if (item.required) {
    return {
      label: "Required",
      tone: "required",
    };
  }

  const conditionalLabel =
    PROFESSIONAL_KYC_CONDITIONAL_LABELS[
      item.name
    ];

  if (conditionalLabel) {
    return {
      label: conditionalLabel,
      tone:
        conditionalLabel === "Optional"
          ? "optional"
          : "conditional",
    };
  }

  return {
    label: "Optional",
    tone: "optional",
  };
};

